<script>
function switchTipsTab(tabName) {
    document.getElementById('tipsTabSection').style.display = tabName === 'tips' ? 'block' : 'none';
    document.getElementById('aiTabSection').style.display = tabName === 'ai' ? 'block' : 'none';
    document.getElementById('bookmarksTabSection').style.display = tabName === 'bookmarks' ? 'block' : 'none';

    document.getElementById('tabTipsBtn').classList.toggle('active', tabName === 'tips');
    document.getElementById('tabAiBtn').classList.toggle('active', tabName === 'ai');
    document.getElementById('tabBookmarksBtn').classList.toggle('active', tabName === 'bookmarks');
}

function saveTipBookmark(title, text) {
    showDemoMessage('Tip pinned and bookmarked to your saved tips!');
}

function bookmarkCurrentAiInsight() {
    showDemoMessage('Monthly AI Insight bookmarked to your references!');
}

function dismissTipElement(btn) {
    const card = btn.closest('.tip-panel');
    if (card) {
        card.style.opacity = '0';
        card.style.transform = 'scale(0.95)';
        setTimeout(() => card.remove(), 250);
    }
}

function openAddNoteModal() {
    const modal = document.getElementById('noteModal');
    if (modal) {
        modal.classList.add('show');
        modal.setAttribute('aria-hidden', 'false');
    }
}

function closeNoteModal() {
    const modal = document.getElementById('noteModal');
    if (modal) {
        modal.classList.remove('show');
        modal.setAttribute('aria-hidden', 'true');
    }
}

function handleSaveNote(e) {
    e.preventDefault();
    showDemoMessage('Note saved to bookmarks.');
    closeNoteModal();
}
</script>
